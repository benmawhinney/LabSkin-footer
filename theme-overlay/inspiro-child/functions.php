/**
 * Enqueue parent and child stylesheets.
 *
 * Inspiro loads its main CSS itself (handle "inspiro-style"), so the child
 * stylesheet depends on it to make sure child rules load last.
 */
function inspiro_child_enqueue_styles() {
	$parent = wp_get_theme( 'inspiro' );

	wp_enqueue_style(
		'inspiro-parent',
		get_template_directory_uri() . '/style.css',
		array(),
		$parent->get( 'Version' )
	);

	wp_enqueue_style(
		'inspiro-child',
		get_stylesheet_uri(),
		array( 'inspiro-parent', 'inspiro-style' ),
		wp_get_theme()->get( 'Version' )
	);

	if ( is_page_template( 'page-footer-lab.php' ) ) {
		wp_enqueue_style(
			'inspiro-child-skin-footer',
			get_stylesheet_directory_uri() . '/assets/css/skin-footer.css',
			array(),
			wp_get_theme()->get( 'Version' )
		);

		wp_enqueue_style(
			'inspiro-child-footer-lab',
			get_stylesheet_directory_uri() . '/assets/css/footer-lab.css',
			array( 'inspiro-parent', 'inspiro-style', 'inspiro-child-skin-footer', 'inspiro-child' ),
			wp_get_theme()->get( 'Version' )
		);

		wp_enqueue_script(
			'inspiro-child-skin-footer',
			get_stylesheet_directory_uri() . '/assets/js/skin-footer.js',
			array(),
			wp_get_theme()->get( 'Version' ),
			true
		);

		wp_enqueue_script(
			'inspiro-child-footer-lab',
			get_stylesheet_directory_uri() . '/assets/js/footer-lab.js',
			array( 'inspiro-child-skin-footer' ),
			wp_get_theme()->get( 'Version' ),
			true
		);
	}

	if ( is_front_page() ) {
		inspiro_child_enqueue_footer_treatment_assets();
		wp_enqueue_script(
			'inspiro-child-model-explorer-host',
			get_stylesheet_directory_uri() . '/assets/js/model-explorer-host.js',
			array(),
			(string) filemtime( get_stylesheet_directory() . '/assets/js/model-explorer-host.js' ),
			true
		);
	}
}
add_action( 'wp_enqueue_scripts', 'inspiro_child_enqueue_styles', 20 );

/**
 * Enqueue the treatment previews used by the homepage footer selector.
 */
function inspiro_child_enqueue_footer_treatment_assets() {
	$theme_version = wp_get_theme()->get( 'Version' );
	$asset_version = static function ( $relative_path ) use ( $theme_version ) {
		$asset_path = get_stylesheet_directory() . $relative_path;
		return file_exists( $asset_path ) ? (string) filemtime( $asset_path ) : $theme_version;
	};

	wp_enqueue_style(
		'inspiro-child-skin-footer',
		get_stylesheet_directory_uri() . '/assets/css/skin-footer.css',
		array(),
		$asset_version( '/assets/css/skin-footer.css' )
	);

	wp_enqueue_style(
		'inspiro-child-footer-lab',
		get_stylesheet_directory_uri() . '/assets/css/footer-lab.css',
		array( 'inspiro-parent', 'inspiro-style', 'inspiro-child-skin-footer', 'inspiro-child' ),
		$asset_version( '/assets/css/footer-lab.css' )
	);

	wp_enqueue_script(
		'inspiro-child-skin-footer',
		get_stylesheet_directory_uri() . '/assets/js/skin-footer.js',
		array(),
		$asset_version( '/assets/js/skin-footer.js' ),
		true
	);

	wp_enqueue_script(
		'inspiro-child-footer-lab-preview-animation',
		get_stylesheet_directory_uri() . '/assets/js/footer-lab-preview-animation.js',
		array(),
		$asset_version( '/assets/js/footer-lab-preview-animation.js' ),
		true
	);

	wp_enqueue_script(
		'inspiro-child-footer-lab',
		get_stylesheet_directory_uri() . '/assets/js/footer-lab.js',
		array( 'inspiro-child-skin-footer', 'inspiro-child-footer-lab-preview-animation' ),
		$asset_version( '/assets/js/footer-lab.js' ),
		true
	);

	$mesh_module_url = get_stylesheet_directory_uri() . '/assets/js/footer-mesh.js?ver=' . rawurlencode( $asset_version( '/assets/js/footer-mesh.js' ) );
	wp_add_inline_script(
		'inspiro-child-footer-lab',
		'window.footerMeshModuleUrl = ' . wp_json_encode( $mesh_module_url ) . ';',
		'before'
	);
}

/**
 * Keep the externally previewable M&C staging copy out of search indexes.
 *
 * The Labskin production host is deliberately not included in this guard.
 *
 * @param array $robots Robots directives generated by WordPress.
 * @return array
 */
function inspiro_child_noindex_mischiefandcraft_staging( $robots ) {
	$host = strtolower( (string) wp_parse_url( home_url(), PHP_URL_HOST ) );

	if ( ! in_array( $host, array( 'mischiefandcraft.com', 'www.mischiefandcraft.com' ), true ) ) {
		return $robots;
	}

	$robots['noindex']  = true;
	$robots['nofollow'] = true;

	return $robots;
}
add_filter( 'wp_robots', 'inspiro_child_noindex_mischiefandcraft_staging' );

/**
 * Add a response-header noindex guard to the M&C staging host.
 *
 * @param array $headers WordPress response headers.
 * @return array
 */
function inspiro_child_noindex_mischiefandcraft_headers( $headers ) {
	$host = strtolower( (string) wp_parse_url( home_url(), PHP_URL_HOST ) );

	if ( in_array( $host, array( 'mischiefandcraft.com', 'www.mischiefandcraft.com' ), true ) ) {
		$headers['X-Robots-Tag'] = 'noindex, nofollow';
	}

	return $headers;
}
add_filter( 'wp_headers', 'inspiro_child_noindex_mischiefandcraft_headers' );

/**
 * Register the footer menu locations.
 *
 * Each location is one footer column (see template-parts/footer/footer-columns.php).
 * Assign menus in Appearance → Menus → Manage Locations; the menu's name is
 * used as the column heading.
 */
function inspiro_child_register_footer_menus() {
	$locations = array();

	for ( $i = 1; $i <= 5; $i++ ) {
		/* translators: %d: footer column number */
		$locations[ "footer-$i" ] = sprintf( __( 'Footer column %d', 'inspiro-child' ), $i );
	}

	register_nav_menus( $locations );
}
add_action( 'after_setup_theme', 'inspiro_child_register_footer_menus' );

/**
 * Copy the parent theme's Customizer settings on first activation.
 *
 * WordPress stores Customizer settings per theme, so activating a child theme
 * would otherwise reset the logo, colours, header image etc. This runs once:
 * parent settings are merged in underneath any the child already has, then a
 * flag is stored so later re-activations don't overwrite child changes.
 *
 * Priority 1 so it runs before core's menu-location mapping on this hook.
 */
function inspiro_child_import_parent_mods() {
	if ( get_option( 'inspiro_child_mods_imported' ) ) {
		return;
	}

	$parent_mods = get_option( 'theme_mods_inspiro' );

	if ( is_array( $parent_mods ) ) {
		$child_mods = get_option( 'theme_mods_' . get_stylesheet() );
		$child_mods = is_array( $child_mods ) ? $child_mods : array();

		update_option( 'theme_mods_' . get_stylesheet(), array_merge( $parent_mods, $child_mods ) );
	}

	update_option( 'inspiro_child_mods_imported', 1 );
}
add_action( 'after_switch_theme', 'inspiro_child_import_parent_mods', 1 );
